export function catalogueEntry(id: string): CargoCatalogueEntry | undefined {
  return CARGO_CATALOGUE.find((c) => c.id === id)
}

export function catalogueByName(name: string): CargoCatalogueEntry | undefined {
  return CARGO_CATALOGUE.find((c) => c.name.toLowerCase() === name.toLowerCase())
}
